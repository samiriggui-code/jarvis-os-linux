def check(label: str, cond: bool, detail: str = "") -> None:
    status = "OK" if cond else "FAIL"
    suffix = f" — {detail}" if detail else ""
    print(f"  [{status}] {label}{suffix}")
    if not cond:
        raise SystemExit(1)


async def run(uri: str) -> None:
    try:
        import websockets
    except ImportError:
        print("FAIL: pip install websockets")
        raise SystemExit(2)

    print(f"AUTH_SMOKE_TEST · WS {uri}")
    jpeg = _tiny_jpeg_b64()
    print(f"  jpeg_b64 size={len(jpeg)}")

    async with websockets.connect(uri, open_timeout=8, max_size=8 * 1024 * 1024) as ws:
        # Drain boot chatter briefly
        try:
            await asyncio.wait_for(ws.recv(), timeout=0.5)
        except asyncio.TimeoutError:
            pass

        await ws.send(json.dumps({"type": "holomat", "action": "status"}))
        face_ready = None
        deadline = time.monotonic() + 3.0
        while time.monotonic() < deadline:
            try:
                raw = await asyncio.wait_for(ws.recv(), timeout=1.0)
            except asyncio.TimeoutError:
                break
            data = json.loads(raw)
            if data.get("type") == "holomat_status":
                face_ready = data.get("face_engine")
                print(f"  holomat_status face_engine={face_ready} algo={data.get('algo')}")
                break

        check("FaceEngine prêt (status)", face_ready is True or face_ready is None,
              "None=status non reçu, on tente face_frame quand même" if face_ready is None else "")

        t0 = time.monotonic()
        await ws.send(json.dumps({
            "type": "holomat",
            "action": "face_frame",
            "mode": "verify",
            "jpeg_b64": jpeg,
        }))

        got = None
        while time.monotonic() - t0 < 5.0:
            try:
                raw = await asyncio.wait_for(ws.recv(), timeout=5.0 - (time.monotonic() - t0))
            except asyncio.TimeoutError:
                break
            data = json.loads(raw)
            t = data.get("type")
            if t in ("FACE_PROGRESS", "FACE_SUCCESS", "FACE_FAILED", "holomat_error"):
                got = data
                break

        elapsed = time.monotonic() - t0
        check("4. face_frame reçu < 5s", got is not None and elapsed < 5.0,
              f"elapsed={elapsed:.3f}s type={got.get('type') if got else None}")

        assert got is not None
        if got.get("type") == "holomat_error":
            check("5. FaceEngine a traité l'image", False, str(got.get("error")))
        else:
            # Réponse FACE_* = handler + runner + (souvent) decode JPEG OK
            check(
                "5. FaceEngine a traité l'image (FACE_*)",
                got.get("type") in ("FACE_PROGRESS", "FACE_SUCCESS", "FACE_FAILED"),
                f"type={got.get('type')} reason={got.get('reason')} found={got.get('face_found')}",
            )

    print("\nAUTH_SMOKE_TEST critères 4–5 : PASS")


def main() -> None:
    uri = os.environ.get("JARVIS_CORE_WS", "ws://127.0.0.1:8765")
    asyncio.run(run(uri))


